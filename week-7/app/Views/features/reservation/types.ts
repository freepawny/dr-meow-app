/* ==========================================================================
   IMPORTS & TYPES
   ========================================================================== */
import type {
    BackendCat,
    BackendCustomer,
    BackendReservation,
    BackendService
} from "@/services/types";

/* ==========================================================================
   DOMAIN OPTION TYPES
   ========================================================================== */
/** Supported weight bracket keys matching backend Service tier_prices. */
export type ReservationWeightTier = "<2" | ">2" | ">5";

/** Customer registration mode inside the reservation modal. */
export type CustomerBookingMode = "new" | "existing";

/** Supported fulfillment icon keys for service methods. */
export type ServiceMethodIconKey = "pickup" | "home" | "dropoff" | "wait";

/** Descriptor for selectable service fulfillment method options. */
export interface ServiceMethodOption {
    value: string;
    label: string;
    subLabel: string;
    iconKey: ServiceMethodIconKey;
    requiresHomeAddress: boolean;
}

/** Descriptor for quick-select cat weight tier presets. */
export interface WeightPresetOption {
    tier: ReservationWeightTier;
    label: string;
    subLabel: string;
    defaultWeight: string;
}

/** Descriptor for quick-select time, branch, temperament, and medical presets. */
export interface QuickChipOption {
    value: string;
    label: string;
    subLabel?: string;
}

/* ==========================================================================
   FORM STATE & VALIDATION TYPES
   ========================================================================== */
/** Unified form state values for the reservation workflow. */
export interface ReservationFormValues {
    /** Whether customer is registering as new or selecting an existing profile. */
    bookingMode: CustomerBookingMode;
    /** Selected service package identifier. */
    selectedServiceId: string;
    /** Chosen service delivery method name. */
    serviceMethod: string;
    /** Notification reminder toggle preference. */
    notificationH1: boolean;
    /** Full name of the customer for new bookings. */
    customerName: string;
    /** WhatsApp contact number for new bookings. */
    phoneNumber: string;
    /** Scheduled arrival date in YYYY-MM-DD format. */
    scheduleDate: string;
    /** Operational time slot string. */
    timeSlot: string;
    /** Delivery address or chosen branch location string. */
    address: string;
    /** Cat's name for new bookings. */
    catName: string;
    /** Selected cat breed. */
    catBreed: string;
    /** Cat weight input value string. */
    catWeight: string;
    /** Cat temperament selection. */
    catTemperament: string;
    /** Physical condition or medical complaints selection. */
    medicalHistory: string;
    /** Selected customer ID when booking in existing mode. */
    selectedCustomerId: string;
    /** Selected cat ID when booking in existing mode. */
    selectedCatId: string;
}

/** Field-level validation errors keyed by form field name. */
export type ReservationFormErrors = Partial<
    Record<keyof ReservationFormValues, string>
>;

/** Type-safe updater callback for modifying a single form field. */
export type UpdateReservationFieldFn = <K extends keyof ReservationFormValues>(
    field: K,
    value: ReservationFormValues[K]
) => void;

/** Snapshot of completed booking details shown in the confirmation view. */
export interface ReservationSuccessSummary {
    /** Persisted reservation entity returned from the backend. */
    reservation: BackendReservation;
    /** Resolved pet owner name. */
    customerName: string;
    /** Resolved cat name. */
    catName: string;
    /** Resolved cat body weight in kg. */
    catWeight: number;
    /** Formatted service name. */
    serviceName: string;
    /** Formatted human-readable schedule label. */
    scheduleLabel: string;
}

/** Context payload used to construct a WhatsApp confirmation link. */
export interface WhatsappMessagePayload {
    /** Optional reservation reference code generated by backend. */
    reservationCode?: string;
    /** Active service entity record. */
    service: BackendService | undefined;
    /** Selected fulfillment method string. */
    serviceMethod: string;
    /** Customer booking mode. */
    bookingMode: CustomerBookingMode;
    /** Current form field values. */
    values: ReservationFormValues;
    /** Selected existing customer record if applicable. */
    existingCustomer: BackendCustomer | undefined;
    /** Selected existing cat record if applicable. */
    existingCat: BackendCat | undefined;
    /** Computed numeric body weight in kg. */
    effectiveWeight: number;
    /** Total calculated fee in IDR. */
    totalBill: number;
}
